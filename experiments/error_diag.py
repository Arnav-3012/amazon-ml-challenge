"""Step 0 error diagnosis of submission B (stage 1 + stage 2 carry20) on its OOF (b) -> docs/error_diagnosis.md.

Read-only. B's decision is rebuilt from oof_krish (p2_full, t from stage2.json) and asserted equal to stage2.json.
Per S1 (b-world scope): TP, FP, FN_block (true pairs not in the v1 candidates), FN_model (true pairs in candidates,
not predicted). Budget = macro F0.5 gain if only that error type were fixed.
Run from repo root: BER_PATH_oof_dir=oof_krish .venv/bin/python experiments/error_diag.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "code" / "business_entity_resolution"))
from src.block import norm_path  # noqa: E402
from src.cv_full import SEED, drop_mask, s1_table  # noqa: E402
from src.decide import f05_vec  # noqa: E402
from src.features import id_key  # noqa: E402
from src.io import load_gt_pairs, path  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "docs" / "error_diagnosis.md"
TEST_SHARE = {"France": 259452, "India": 809986, "US": 663106}
COMMON = ["shree", "shri", "sri", "om", "global", "new", "india", "indian", "national", "international", "royal",
          "star", "city", "the", "services", "enterprises", "traders", "solutions", "group", "center", "centre"]
pl.Config.set_tbl_rows(40)
pl.Config.set_fmt_str_lengths(60)
pl.Config.set_tbl_width_chars(250)


def md(df: pl.DataFrame) -> str:
    cols = df.columns
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.iter_rows():
        out.append("| " + " | ".join(f"{v:.4f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def ents(split: str) -> pl.DataFrame:
    cols = ["entity_id", "business_name", "business_address", "country", "core_name", "name_tokens", "addr_tokens",
            "has_address", "is_nonascii_raw"]
    return pl.concat([pl.read_parquet(norm_path(split, n), columns=cols) for n in (1, 2, 3)]).with_columns(
        k=id_key("entity_id"))


def main() -> None:
    O = path("oof_dir")
    s2 = json.loads((O / "stage2.json").read_text())
    t, ref = s2["full"]["best_t"], s2["full"]["macro_f05"]
    s1 = s1_table(1.0)
    n = s1.height
    scope = ~drop_mask(n, SEED + 2000)
    oof = (pl.read_parquet(O / "oof_full.parquet", columns=["_i", "s1k", "reck", "label", "p_td"])
           .filter(pl.col("p_td").is_not_null())
           .join(pl.read_parquet(O / "oof_stage2.parquet", columns=["_i", "p2_full"]), on="_i", how="left")
           .join(s1.select("s1k", "code"), on="s1k", how="left"))
    top = (oof.sort(["reck", "p2_full", "code"], descending=[False, True, False])
           .with_columns(top=pl.col("reck").is_first_distinct()))
    top = top.with_columns(pred=pl.col("top") & (pl.col("p2_full") >= t))
    code, pred, lab = top["code"].to_numpy(), top["pred"].to_numpy(), top["label"].to_numpy() == 1
    tp = np.bincount(code[pred & lab], minlength=n)
    npred = np.bincount(code[pred], minlength=n)
    incand = np.bincount(code[lab], minlength=n)
    ntrue = s1["ntrue"].to_numpy()
    f = f05_vec(tp, npred, ntrue)
    assert abs(f[scope].mean() - ref) < 1e-9, (f[scope].mean(), ref)
    fp, fn_b, fn_m = npred - tp, ntrue - incand, incand - tp
    fix = {"blocking misses": f05_vec(tp + fn_b, npred + fn_b, ntrue),
           "false positives": f05_vec(tp, tp, ntrue),
           "matcher FN (in candidates)": f05_vec(tp + fn_m, npred + fn_m, ntrue)}
    ctry = s1["country"].to_numpy()
    L = ["# Error diagnosis of submission B (OOF (b), stage 1 + stage 2)", "",
         f"Generated by `experiments/error_diag.py`, seed 42. Scope: {int(scope.sum()):,} S1s of the test-density "
         f"world. B rebuilt from `oof_krish` (t = {t}): macro F0.5 {f[scope].mean():.5f} (= stage2.json). Cost = macro-F0.5 "
         "gain if ONLY that error type were fixed (they overlap, so the costs are not additive). LB-weighted = the "
         "country cost x its test share (France has no labels: US/India only).", "", "## 1. Error budget by country", ""]
    rows = []
    for c in ["India", "US"]:
        m = scope & (ctry == c)
        single = ntrue == 0
        rows.append({"country": c, "S1": int(m.sum()), "F0.5": float(f[m].mean()),
                     **{f"cost {k}": float((v[m] - f[m]).mean()) for k, v in fix.items()},
                     "singleton w/ pred %": float(100 * (single & (npred > 0))[m].sum() / m.sum()),
                     "non-singleton empty %": float(100 * (~single & (npred == 0))[m].sum() / m.sum()),
                     "FP pairs": int(fp[m].sum()), "FN block": int(fn_b[m].sum()), "FN model": int(fn_m[m].sum())})
    bud = pl.DataFrame(rows)
    L += [md(bud), ""]
    tot = sum(TEST_SHARE.values())
    lbw = {k: sum(r[f"cost {k}"] * TEST_SHARE[r["country"]] / tot for r in rows) for k in fix}
    L += ["LB-weighted cost (US/India shares of test only, France excluded): " +
          ", ".join(f"{k} {v:.4f}" for k, v in lbw.items()), "",
          "Empty-set decisions: `singleton w/ pred` = S1 with no true match that got a prediction (scores 0 instead of 1); "
          "`non-singleton empty` = S1 with true matches that got nothing (0). Each costs 1/N_S1 of macro F0.5.", ""]

    # ---- row-level patterns
    gt = load_gt_pairs().select(s1k=id_key("s1_id"), reck=id_key("match_id"))
    alive = s1.filter(pl.Series(scope)).select("s1k", "code", "country", "ntrue")
    true_rec = oof.filter(pl.col("label") == 1).group_by("reck").agg(true_code=pl.col("code").first())
    pr = (top.filter("pred").join(true_rec, on="reck", how="left")
          .join(alive.select("code", "country", "ntrue"), on="code", how="inner"))
    pr = pr.with_columns(pat=pl.when(pl.col("label") == 1).then(pl.lit("TP"))
                         .when(pl.col("ntrue") == 0).then(pl.lit("FP: singleton S1 given a match"))
                         .when(pl.col("true_code").is_null()).then(pl.lit("FP: distractor record (true S1 absent)"))
                         .otherwise(pl.lit("FP: record's true S1 is another candidate")))
    tr = top.filter(pl.col("label") == 1).join(alive.select("code", "country"), on="code", how="inner")
    rec_top = top.filter("top").select("reck", top_code="code", top_p="p2_full")
    tr = tr.join(rec_top, on="reck", how="left").with_columns(
        pat=pl.when(pl.col("pred")).then(pl.lit("TP"))
        .when(pl.col("top_code") == pl.col("code")).then(pl.lit("FN: argmax right, p below t"))
        .otherwise(pl.lit("FN: record argmax went to another S1")))
    miss = (gt.join(alive.select("s1k", "country"), on="s1k", how="inner")
            .join(oof.select("s1k", "reck"), on=["s1k", "reck"], how="anti").with_columns(pat=pl.lit("FN: blocking miss")))
    E = ents("train")
    ek = E.select("k", "business_name", "business_address", "core_name", "name_tokens", "addr_tokens", "has_address",
                  "is_nonascii_raw")
    s1e = ek.rename({c: f"s1_{c}" for c in ek.columns if c != "k"}).rename({"k": "s1k"})
    rce = ek.rename({c: f"r_{c}" for c in ek.columns if c != "k"}).rename({"k": "reck"})
    s1k_of = s1.select("code", "s1k")
    allerr = pl.concat([
        pr.filter(pl.col("pat") != "TP").join(s1k_of, on="code").select("country", "pat", "s1k", "reck", p="p2_full"),
        tr.filter(pl.col("pat") != "TP").join(s1k_of, on="code").select("country", "pat", "s1k", "reck", p="p2_full"),
        miss.select("country", "pat", "s1k", "reck", p=pl.lit(None, pl.Float32))], how="diagonal_relaxed")
    allerr = allerr.join(s1e, on="s1k", how="left").join(rce, on="reck", how="left")
    allerr = allerr.with_columns(
        shared_name=pl.col("s1_name_tokens").list.set_intersection("r_name_tokens").list.len(),
        shared_addr=pl.col("s1_addr_tokens").list.set_intersection("r_addr_tokens").list.len(),
        script_mix=pl.col("r_is_nonascii_raw") & ~pl.col("s1_is_nonascii_raw"),
        rec_noaddr=~pl.col("r_has_address"),
        common_tok=pl.col("s1_name_tokens").list.eval(pl.element().is_in(COMMON)).list.any())
    L += ["## 2. Error patterns per country (counts; 5 real examples each)", "",
          "Attributes: `script_mix` = raw record non-ASCII while the S1 is ASCII; `rec_noaddr` = record has no address; "
          "`common_tok` = S1 core name contains a very common token (shree/om/global/...); `shared_*` = normalised "
          "tokens in common.", ""]
    for c in ["India", "US"]:
        e = allerr.filter(pl.col("country") == c)
        s = (e.group_by("pat").agg(n=pl.len(), script_mix_pct=pl.col("script_mix").mean() * 100,
                                   rec_noaddr_pct=pl.col("rec_noaddr").mean() * 100,
                                   common_tok_pct=pl.col("common_tok").mean() * 100,
                                   no_shared_name_pct=(pl.col("shared_name") == 0).mean() * 100)
             .sort("n", descending=True))
        L += [f"### {c}", "", md(s), ""]
        for pat in s["pat"].head(5):
            ex = e.filter(pl.col("pat") == pat).sample(5, seed=SEED)
            L += [f"**{pat}**", "", md(ex.select(
                S1=pl.col("s1_business_name") + " | " + pl.col("s1_business_address"),
                record=pl.col("r_business_name") + " | " + pl.col("r_business_address"),
                p=pl.col("p").round(3).cast(pl.Utf8).fill_null("-"))), ""]

    # ---- blocking-miss reasons (all train misses of the scope S1s)
    b = allerr.filter(pl.col("pat") == "FN: blocking miss").with_columns(
        abbrev=(pl.col("r_core_name").str.replace_all(" ", "").str.len_chars() <= 5)
        & (pl.col("s1_name_tokens").list.len() >= 2))
    b = b.with_columns(reason=pl.when((pl.col("shared_name") == 0) & (pl.col("shared_addr") == 0) & pl.col("script_mix"))
                       .then(pl.lit("no shared token, script mismatch (transliteration)"))
                       .when((pl.col("shared_name") == 0) & (pl.col("shared_addr") == 0)).then(pl.lit("no shared token"))
                       .when(pl.col("abbrev")).then(pl.lit("abbreviated / very short record name"))
                       .when(pl.col("rec_noaddr") & pl.col("common_tok")).then(pl.lit("no address + common-token name"))
                       .when(pl.col("rec_noaddr")).then(pl.lit("record has no address"))
                       .when(pl.col("shared_name") == 0).then(pl.lit("address shared, name changed (rank cut)"))
                       .otherwise(pl.lit("tokens shared, lost to rank cut / df cap")))
    rs = (b.group_by("country", "reason").len().with_columns(
        pct=(pl.col("len") / pl.col("len").sum().over("country") * 100)).sort(["country", "len"], descending=[False, True]))
    L += ["## 3. Why blocking misses were missed (scope S1s, first matching reason)", "", md(rs), "",
          "Token overlap is measured AFTER anyascii transliteration, so a native-script record whose transliteration "
          "differs (हाईटेक फाइनेंस -> 'haaiittek phaainens' vs 'hitech finance') lands in 'name changed'. Split by script:", "",
          md(b.group_by("country", "reason").agg(n=pl.len(), script_mix_pct=pl.col("script_mix").mean() * 100,
                                                  shared_addr_ge2_pct=(pl.col("shared_addr") >= 2).mean() * 100)
             .sort(["country", "n"], descending=[False, True])), ""]

    # ---- shift
    sh = []
    for split in ("train", "test"):
        for nsrc in (1, 2, 3):
            d = pl.read_parquet(norm_path(split, nsrc), columns=["country", "has_address", "is_nonascii_raw", "name_tokens"])
            sh.append(d.group_by("country").agg(n=pl.len(), noaddr=(~pl.col("has_address")).sum(),
                                                nonascii=pl.col("is_nonascii_raw").sum(),
                                                ntok=pl.col("name_tokens").list.len().sum())
                      .with_columns(split=pl.lit(split), src=pl.lit("S1" if nsrc == 1 else "S2/S3")))
    sh = (pl.concat(sh).group_by("split", "country", "src").agg(pl.col("n", "noaddr", "nonascii", "ntok").sum())
          .with_columns(share_pct=pl.col("n") / pl.col("n").sum().over("split", "src") * 100,
                        no_address_pct=pl.col("noaddr") / pl.col("n") * 100,
                        non_ascii_pct=pl.col("nonascii") / pl.col("n") * 100,
                        name_tokens=pl.col("ntok") / pl.col("n"))
          .select("split", "src", "country", "n", "share_pct", "no_address_pct", "non_ascii_pct", "name_tokens")
          .sort("src", "split", "country"))
    L += ["## 4. Train vs test shift", "", md(sh), ""]
    OUT.write_text("\n".join(L))
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
